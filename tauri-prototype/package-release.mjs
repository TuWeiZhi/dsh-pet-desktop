import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const version=JSON.parse(readFileSync(join(here,'package.json'))).version;
const release=join(here,'src-tauri/target/release');
const output=resolve(here,'../dist/tauri-full');mkdirSync(output,{recursive:true});
const name=`dsh-pet-tauri-${version}-setup.exe`;
cpSync(join(release,'bundle/nsis',`dsh-pet-tauri_${version}_x64-setup.exe`),join(output,name));
const hash=file=>createHash('sha256').update(readFileSync(file)).digest('hex');
const manifest={version,size:statSync(join(output,name)).size,sha256:hash(join(output,name))};
writeFileSync(join(output,'tauri-update-manifest.json'),JSON.stringify(manifest)+'\n');
const portable=join(output,'portable');mkdirSync(portable,{recursive:true});
cpSync(join(release,'dsh-pet-tauri.exe'),join(portable,'dsh-pet-tauri.exe'));
cpSync(join(release,'web'),join(portable,'web'),{recursive:true});
const files=dir=>readdirSync(dir,{withFileTypes:true}).flatMap(entry=>entry.isDirectory()?files(join(dir,entry.name)):[join(dir,entry.name)]);
const originals=JSON.parse(readFileSync(join(portable,'web/reuse-manifest.json')));
for(const item of originals)if(hash(join(portable,'web',item.path))!==item.sha256)throw Error('Reused file changed: '+item.path);
const report={...manifest,installer:name,payloadBytes:files(portable).reduce((n,f)=>n+statSync(f).size,0),nativeExeBytes:statSync(join(portable,'dsh-pet-tauri.exe')).size,nodeBytes:statSync(join(portable,'web/host/node.exe')).size,reusedFiles:originals.length,reusedAssets:originals.filter(f=>f.path.startsWith('assets/')).length};
writeFileSync(join(output,'build-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
